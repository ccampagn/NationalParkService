IF OBJECT_ID('dbo.Campground', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.Campground
    (
        CampgroundId   INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_Campground PRIMARY KEY,
        ParkId         INT               NOT NULL CONSTRAINT FK_Campground_Park REFERENCES dbo.Park (ParkId),
        CampgroundName NVARCHAR(100)     NOT NULL,
        NightlyRate    INT               NOT NULL,
        MaxGuests      INT               NOT NULL CONSTRAINT DF_Campground_MaxGuests DEFAULT 6,
        CONSTRAINT UQ_Campground_Park_Name UNIQUE (ParkId, CampgroundName)
    );
END
GO

